package corpus

import (
	"flag"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

var update = flag.Bool("update", false, "rewrite docs/corpus-report.md")

func TestCorpusLoadsAndIsStratified(t *testing.T) {
	var report strings.Builder
	report.WriteString("# Corpus distribution report\n\nGenerated by `go test ./internal/corpus -update`. All records are synthetic; see `testdata/corpus/README.md`.\n\n")
	seen := map[string]bool{}
	for _, split := range []string{"commands", "heldout"} {
		recs, err := Load(split)
		if err != nil {
			t.Fatal(err)
		}
		if len(recs) == 0 {
			t.Fatalf("%s: empty split", split)
		}
		for _, r := range recs {
			if seen[r.ID] {
				t.Errorf("duplicate id %s", r.ID)
			}
			seen[r.ID] = true
			if len(r.Tags) < 2 {
				t.Errorf("%s: needs stratification tags", r.ID)
			}
			if len(r.Labels.Requests)+len(r.Labels.Inferences)+len(r.Labels.Unknowns) == 0 {
				t.Errorf("%s: unlabeled", r.ID)
			}
		}
		report.WriteString(Report(split, recs))
	}
	if *update {
		path := filepath.Join(Dir(), "..", "..", "docs", "corpus-report.md")
		if err := os.WriteFile(path, []byte(report.String()), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}
