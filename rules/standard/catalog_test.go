package standard

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"github.com/lastpersonlabs/toolparser/rules"
)

var update = flag.Bool("update", false, "rewrite docs/rules.md")

// TestCatalog checks every rule registers cleanly and documents its grammar,
// and regenerates docs/rules.md with -update.
func TestCatalog(t *testing.T) {
	all := Rules()
	if _, err := rules.NewRegistry(all...); err != nil {
		t.Fatal(err)
	}
	var b strings.Builder
	b.WriteString("# Standard rule catalog\n\nGenerated by `go test ./rules/standard -update`. Every rule assumes the executable name denotes the standard program; functions, aliases and shadowed binaries defined in the analyzed program override that assumption. Recognizing an operand is not proof that the file was accessed.\n\n| Rule | Version | Executables | Option grammar / boundary |\n|---|---|---|---|\n")
	sorted := append([]rules.Rule(nil), all...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].ID < sorted[j].ID })
	for _, r := range sorted {
		if r.Doc == "" {
			t.Errorf("rule %s has no documentation", r.ID)
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", r.ID, r.Version, strings.Join(r.Executables, ", "), strings.ReplaceAll(r.Doc, "|", "\\|"))
	}
	if *update {
		if err := os.WriteFile(filepath.Join("..", "..", "docs", "rules.md"), []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}
