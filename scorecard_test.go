// TestScorecard computes the release scorecard over the corpus and, with
// -update, writes docs/scorecard.md. It asserts the release invariants on
// every record: acceptance, validity, determinism, no fabricated
// observations, and explicit diagnostics for every partial result.
func TestScorecard(t *testing.T) {
	e := langEngine(t)
	var b strings.Builder
	b.WriteString("# Release scorecard\n\nGenerated by `go test . -run TestScorecard -update` over `testdata/corpus`. The corpus is synthetic (see `testdata/corpus/README.md`): these are coverage and invariant measurements, not accuracy against real sessions. The 99% precision gate for narrow action/resource classifications cannot be measured until a labeled real corpus exists; labels here were reviewed by hand and the analyzer's output was checked against them in `TestCorpusLabels`.\n\n")
	for _, split := range []string{"commands", "heldout"} {
		recs, err := corpus.Load(split)
		if err != nil {
			t.Fatal(err)
		}
		var accepted, parsed, partial, withActions, limitHits int
		families := map[string]int{}
		bases := map[model.Basis]int{}
		diags := map[string]int{}
		knowledge := map[model.Knowledge]int{}
		for _, r := range recs {
			var inv model.Invocation
			if err := json.Unmarshal(r.Invocation, &inv); err != nil {
				t.Fatalf("%s: %v", r.ID, err)
			}
			a, err := e.Analyze(context.Background(), inv)
			if err != nil {
				t.Fatalf("%s: %v", r.ID, err)
			}
			accepted++
			again, _ := e.Analyze(context.Background(), inv)
			if !reflect.DeepEqual(a, again) {
				t.Fatalf("%s: not deterministic", r.ID)
			}
			if len(a.Observations) != 0 {
				t.Fatalf("%s: fabricated observation", r.ID)
			}
			syntaxOK := true
			for _, n := range a.Nodes {
				if n.Syntax == model.SyntaxInvalid || n.Syntax == model.SyntaxPartial {
					syntaxOK = false
				}
			}
			if syntaxOK {
				parsed++
			}
			if a.Partial {
				partial++
				if len(a.Diagnostics) == 0 {
					t.Fatalf("%s: partial without diagnostics", r.ID)
				}
			}
			if len(a.Actions) > 0 {
				withActions++
			}
			for _, act := range a.Actions {
				families[act.Kind.Family()]++
				bases[act.Evidence.Basis]++
				for _, res := range act.Resources {
					knowledge[res.Knowledge]++
				}
			}
			for _, d := range a.Diagnostics {
				diags[d.Code]++
				if d.Code == model.DiagLimitReached || d.Code == model.DiagBudgetExhausted {
					limitHits++
				}
			}
		}
		fmt.Fprintf(&b, "## %s split (%d records)\n\n", split, len(recs))
		fmt.Fprintf(&b, "| Metric | Value |\n|---|---:|\n| adapter acceptance | %d/%d |\n| syntax success | %d/%d |\n| records with at least one action | %d/%d |\n| partial results (explicit unknowns) | %d/%d |\n| resource-limit incidents | %d |\n\n", accepted, len(recs), parsed, len(recs), withActions, len(recs), partial, len(recs), limitHits)
		writeCounts(&b, "Actions by family", families)
		writeCountsB(&b, "Actions by evidence basis", bases)
		writeCountsK(&b, "Resources by knowledge", knowledge)
		writeCounts(&b, "Diagnostics by code", diags)
	}
	if *update {
		if err := os.WriteFile(filepath.Join("docs", "scorecard.md"), []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func writeCounts(b *strings.Builder, title string, m map[string]int) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	fmt.Fprintf(b, "### %s\n\n| key | count |\n|---|---:|\n", title)
	for _, k := range keys {
		fmt.Fprintf(b, "| %s | %d |\n", k, m[k])
	}
	b.WriteString("\n")
}

func writeCountsB(b *strings.Builder, title string, m map[model.Basis]int) {
	out := map[string]int{}
	for k, v := range m {
		out[string(k)] = v
	}
	writeCounts(b, title, out)
}

func writeCountsK(b *strings.Builder, title string, m map[model.Knowledge]int) {
	out := map[string]int{}
	for k, v := range m {
		out[string(k)] = v
	}
	writeCounts(b, title, out)
}

// TestCorpusLabels checks the reviewed labels against the analyzer where
// a label names an action kind: each labeled kind must appear.
func TestCorpusLabels(t *testing.T) {
	e := langEngine(t)
	for _, split := range []string{"commands", "heldout"} {
		recs, _ := corpus.Load(split)
		for _, r := range recs {
			var inv model.Invocation
			json.Unmarshal(r.Invocation, &inv)
			a, err := e.Analyze(context.Background(), inv)
			if err != nil {
				t.Fatal(err)
			}
			got := map[string]bool{}
			for _, act := range a.Actions {
				got[string(act.Kind)] = true
			}
			for _, label := range append(r.Labels.Inferences, r.Labels.Requests...) {
				kind := strings.Fields(label)[0]
				if !strings.Contains(kind, ".") || strings.Contains(kind, "(") {
					continue
				}
				kind = strings.TrimSuffix(kind, ";")
				if !model.ActionKind(kind).Known() {
					continue
				}
				if !got[kind] {
					t.Errorf("%s: label %q not produced; got %s", r.ID, label, describeActions(a))
				}
			}
		}
	}
}
